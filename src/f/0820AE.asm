	swap	d1
	clr.w	d1
	add.l	d1,d0
	move.w	(a4,d0.l),-$2(a6)
	ext.l	d7
	move.l	d7,d0
	move.l	d0,d1
	mulu.w	#$C,d0
	swap	d1
	mulu.w	#$C,d1
	swap	d1
	clr.w	d1
	add.l	d1,d0
	move.w	$2(a4,d0.l),d4
	ext.l	d7
	move.l	d7,d0
	move.l	d0,d1
	mulu.w	#$C,d0
	swap	d1
	mulu.w	#$C,d1
	swap	d1
