"""Export the recompilation handoff (phase 2 input) into build/recomp/.

    uv run tools/handoff.py

Files (see docs/RECOMP_HANDOFF.md):
  code_addrs.txt     every instruction start (segagenesisrecomp `code_addrs_file`)
  functions.csv      addr,name,end,purpose  (one row per src/f function file)
  jumptable.csv      index,a5_disp,jmp_addr,target,target_name,kind(code|data)
  ram_globals.csv    name,a5_offset,ram_addr,comment
  seeds.toml         [functions] extra = every function entry (discovery seeds)
  identity.json      ROM hash, entry/IRQ vectors, A5, memory facts
"""
from __future__ import annotations

import csv
import json
import re
import shutil
import struct

import build

ROOT = build.ROOT
OUT = ROOT / "build" / "recomp"
A5 = 0x200


def main() -> int:
    lst = ROOT / "build" / "xmen2.lst"
    if not lst.exists():
        print("FAIL: build first (uv run tools/build.py)")
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    rom = build.ROM.read_bytes()
    shutil.copyfile(ROOT / "build" / "xmen2.code_addrs.txt", OUT / "code_addrs.txt")
    code = {int(a, 16) for a in (OUT / "code_addrs.txt").read_text().split()}
    syms: dict[int, str] = {}
    for line in (ROOT / "build" / "symbols.txt").read_text().splitlines():
        n, _, a = line.partition("=$")
        syms.setdefault(int(a, 16), n)

    files = sorted((ROOT / "src" / "f").glob("*.asm"))
    starts = [int(f.stem, 16) for f in files]
    with (OUT / "functions.csv").open("w", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["addr", "name", "end", "purpose"])
        main_text = (ROOT / "xmen2.asm").read_text()
        for i, f in enumerate(files):
            a = starts[i]
            nxt = starts[i + 1] if i + 1 < len(starts) else len(rom)
            body = [x for x in code if a <= x < nxt]
            end = max(body) + 2 if body else a
            name = syms.get(a, f"sub_{a:06X}")
            m = re.search(rf"^; {re.escape(name)} - (.+)$", f.read_text(), re.M)
            w.writerow([f"{a:06X}", name, f"{end:06X}", m.group(1).strip() if m else ""])
    with (OUT / "jumptable.csv").open("w", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["index", "a5_disp", "jmp_addr", "target", "target_name", "kind"])
        for i in range(2631):
            t = struct.unpack_from(">I", rom, 0x220 + 8 * i + 4)[0]
            w.writerow([i, f"${0x22 + 8 * i:X}", f"{0x222 + 8 * i:06X}", f"{t:06X}", syms.get(t, ""),
                        "code" if t in code else "data"])
    with (OUT / "ram_globals.csv").open("w", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["name", "a5_offset", "ram_addr", "comment"])
        for m in re.finditer(r"^(\w+)\s*=\s*(-?\$[0-9A-Fa-f]+)\s*(?:;\s*(.*))?$",
                             (ROOT / "src" / "ram.asm").read_text(), re.M):
            off = int(m.group(2).replace("$", "0x").replace("-0x", "-0x"), 16)
            w.writerow([m.group(1), m.group(2), f"{(A5 + off) & 0xFFFFFF:06X}", m.group(3) or ""])
    entries = sorted(set(starts))
    (OUT / "seeds.toml").write_text(
        "# Generated by tools/handoff.py from the byte-matching disassembly (ground truth).\n"
        "[functions]\nextra = [\n" + "".join(f"  0x{a:06X},  # {syms.get(a, '')}\n" for a in entries) + "]\n",
        newline="\n")
    vec = lambda n: struct.unpack_from(">I", rom, 4 * n)[0]  # noqa: E731
    ident = {"sha1": build.ROM_SHA1, "rom_size": len(rom), "initial_ssp": f"{vec(0):08X}",
             "entry": f"{vec(1):06X}", "hint_irq4": f"{vec(28):06X}", "vint_irq6": f"{vec(30):06X}",
             "a5": f"{A5:06X}", "a5_note": "constant; -d(a5) globals wrap to RAM ($200-d)&$FFFFFF, "
                                         "+d(a5) with d=$22+8i is jump-table entry i at ROM $220",
             "irq_hook_pointers": {f"${p:X}": f"{struct.unpack_from('>I', rom, p)[0]:06X}" for p in (0x210, 0x214, 0x218)},
             "functions": len(entries), "instructions": len(code)}
    (OUT / "identity.json").write_text(json.dumps(ident, indent=1), newline="\n")
    print(f"OK: build/recomp/ written ({len(entries)} functions, {len(code)} instruction starts)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
